#[derive(Debug, Clone, PartialEq)]
pub enum FstringSeg {
    Lit(String),
    Expr(String),
}

#[derive(Debug, Clone, PartialEq)]
pub enum Token {
    INT(isize),
    FLOAT(f64),
    BOOL(bool),
    STRING(String),
    FSTRING(Vec<FstringSeg>),
    NIL,
    PLUS,
    MINUS,
    STAR,
    SLASH,
    PERCENT,
    DOT,
    DOTDOT,
    CEQ,
    NE,
    LT,
    LE,
    GT,
    GE,
    AND,
    OR,
    LAND,
    LOR,
    XOR,
    NOT,
    LPAREN,
    RPAREN,
    LBRACE,
    RBRACE,
    LBRACKET,
    RBRACKET,
    EQ,
    PLUSEQ,
    MINUSEQ,
    PLUSPLUS,
    MINUSMINUS,
    COLON,
    COMMA,
    SEMICOLON,
    LET,
    FUN,
    FOR,
    IN,
    EXTERN,
    RET,
    IF,
    ELSE,
    WHILE,
    BREAK,
    CONTINUE,
    TYPEDEF,
    MATCH,
    STRUCT,
    UNION,
    ENUM,
    TYPE(String),
    IDENT(String),
    LAMBDA,
    EOF,
}
